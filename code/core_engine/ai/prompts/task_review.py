"""Task-level checks adapted from hierarchical monitoring and dynamic planning."""

TASK_REVIEW_POLICY = """
审查学习任务的实际可执行性。
1. 先看截止日期、每周预算、连续空档、用户反馈，再确定本轮任务范围。
2. 每条任务有明确材料或材料选择条件、具体动作和范围。后续引用沿用同一材料名称。
3. 限时作答、错因分析、针对性复练、间隔复测按必要依赖衔接。
   可以独立完成、产出不同结果的活动分开；不要把同一完整限时活动切成碎片。
4. estimated_minutes 按具体动作估计；整卷模拟保留真实连续时长。
5. stage 表示目标下的阶段，同一阶段名称一致。只细化近期可安排的任务，
   优先展开未来7天可执行的少量任务，通常3至5项，按实际预算决定，不为凑数量拆分。
   总数最多16项是异常保护，不是生成目标；长期方向和关键截止节点在回答中交代。
6. 不编造成绩、已完成行为、具体题号、材料内容或真实学习效果。
7. 检查重复任务、无效依赖、练习先后颠倒和遗漏核心目标。
8. title 使用简短且可区分的“材料或对象+动作”，通常8至24字；不要截断已有长标题。
   description 独立写明材料选择条件、具体步骤和范围，脱离聊天也能执行。
   rationale 解释安排依据；description 说明做法，二者不要混淆。
"""

FEEDBACK_POLICY = """
把本轮反馈与当前方案逐项对照，再决定是否调整。
先区分用户明确提供的学习结果、错因、可用时间变化与尚待澄清的信息。
例如“听不清”不能直接认定为语速问题；只有用户明确确认后才采用该错因。
按原 index 定位受影响的未完成任务，沿依赖检查后续复练与复测，
优先修改现有条目，保留无关任务与已完成结果。
前置未完成时不要把后续当作已经具备条件；完成勾选不代表已经掌握。
资料或时间不足时，先问最关键的问题，或提出有依据的范围缩减建议。
reply 简述本轮调整依据和增减内容，不展示内部推理。
"""
